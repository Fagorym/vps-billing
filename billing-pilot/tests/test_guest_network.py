    def test_apply_alma_uses_static_mac_bound_network_manager_profiles(self):
        for os_name in ('AlmaLinux 9', 'AlmaLinux 10'):
            with self.subTest(os=os_name), tempfile.TemporaryDirectory() as temporary:
                root = Path(temporary)
                initial = self.cloud_profile(root)
                public_initial = self.cloud_profile(root, 'eth1', 1)
                agent = self.apply_in_guest(root, os_name)
                self.assertEqual(agent.requests[0][7:10], ['/usr/local/libexec/safehost-qga-exec', '/usr/bin/python3', '-c'])
                self.assertFalse(initial.exists())
                self.assertFalse(public_initial.exists())
                private, public = self.read_profile(root, 'private'), self.read_profile(root, 'public')
                self.assertEqual(private['ipv4']['address1'], '10.10.10.20/24')
                self.assertEqual(private['ipv4']['never-default'], 'true')
                self.assertNotIn('gateway', private['ipv4'])
                self.assertEqual(public['ipv4']['address1'], '198.51.100.3/29,198.51.100.1')
                self.assertEqual(public['ipv4']['dns'], '1.1.1.1;')
                for nic, profile in enumerate((private, public)):
                    self.assertEqual(profile['ethernet']['mac-address'], self.network.mac(self.row, nic))
                    self.assertEqual(profile['ipv4']['method'], 'manual')
                    self.assertEqual(profile['ipv6']['method'], 'disabled')
                self.assertEqual(agent.commands[-3:], [
                    ['/usr/bin/nmcli', 'connection', 'reload'],
                    ['/usr/bin/nmcli', '--wait', '15', 'connection', 'up', 'uuid', private['connection']['uuid']],
                    ['/usr/bin/nmcli', '--wait', '15', 'connection', 'up', 'uuid', public['connection']['uuid']]])
                self.assertEqual((root/'etc/cloud/cloud.cfg.d/99-safehost-network.cfg').read_text(), 'network: {config: disabled}\n')
                self.assertTrue(all(path.stat().st_mode & 0o777 == 0o600 for path in self.profiles(root).iterdir()))
                self.assertNotIn('DO-NOT-TRANSPORT-CREDENTIALS', agent.sources[0])
                self.assertIn('def write_network_manager_config', agent.sources[0])
                self.assertFalse((root/'etc/netplan').exists())

